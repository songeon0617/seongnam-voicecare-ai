export function validateEvaluationInventory(): void {
  const cases = VOICECARE_EVALUATION_CASES;
  if (cases.length !== 240 || new Set(cases.map((c) => c.id)).size !== 240) throw new Error("Evaluation requires 240 unique case IDs");
  if (new Set(cases.map((c) => c.question)).size !== 240) throw new Error("Duplicate evaluation question");
  if (cases.filter((c) => c.split === "holdout").length !== 60) throw new Error("Evaluation requires 60 holdout cases");
  if (Object.keys(domains).length !== 20 || Object.values(domains).some((rows) => rows.length !== 8)) throw new Error("Evaluation requires 20 domains × 8");
  if (conversationRows.length !== 40 || boundaryRows.length !== 40) throw new Error("Evaluation requires 40 conversation and 40 boundary cases");
  if (new Set(cases.flatMap((c) => c.existingServiceId ? [c.existingServiceId] : [])).size !== 13) throw new Error("All 13 existing services required");
  const refs = new Set(EVALUATION_EVIDENCE.map((e) => e.id));
  if (cases.some((c) => c.evidenceReferences.some((ref) => !refs.has(ref)))) throw new Error("Unknown evidence reference");
  if (cases.some((c) => c.answerability === "VERIFIED_ANSWERABLE" && !c.evidenceReferences.length)) throw new Error("Verified answerability requires inspected evidence");
}

validateEvaluationInventory();
