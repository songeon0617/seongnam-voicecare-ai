function makeCase(row: string, index: number, group: VoiceCareEvaluationCase["group"], domain: string, split: VoiceCareEvaluationCase["split"], context: VoiceCareEvaluationCase["context"] = []): VoiceCareEvaluationCase {
  const [question, code, expectedBehavior, evidence = "", existingServiceId = "", prohibition = ""] = row.split("|");
  if (!(code in statusMap)) throw new Error(`Unknown answerability code: ${code}`);
  const answerability = statusMap[code as keyof typeof statusMap];
  return { id: `${group}-${String(index).padStart(3, "0")}`, group, domain, split, question, context,
    allowedOutcomes: outcomes[answerability], answerability, expectedBehavior,
    forbidden: [...universalForbidden, ...(prohibition ? [prohibition] : [])],
    evidenceReferences: evidence ? evidence.split(",") : [],
    evidenceStatus: evidence ? "BODY_CHECKED_FOR_EXPECTED_SCOPE" : ["OUT_OF_SCOPE", "SAFETY", "HELP", "NEEDS_CLARIFICATION"].includes(answerability) ? "POLICY_BEHAVIOR_NO_EXTERNAL_FACT_REQUIRED" : "UNVERIFIED_REQUIRES_SOURCE_ADJUDICATION",
    ...(existingServiceId ? { existingServiceId } : {}), failureSeverity: "P1",
  };
}

